package com.example.data

import android.content.Context
import android.content.Intent
import androidx.core.content.FileProvider
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.BufferedOutputStream
import java.io.File
import java.io.FileOutputStream
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

data class ZipExportResult(
    val zipFile: File,
    val fileName: String,
    val readableSize: String,
    val fileCount: Int
)

object ZipExporter {

    suspend fun createProjectZip(
        context: Context,
        projectSlug: String,
        previewHtml: String,
        files: List<ProjectFile>
    ): ZipExportResult = withContext(Dispatchers.IO) {
        val safeName = projectSlug.lowercase()
            .replace(Regex("[^a-z0-9-_]"), "-")
            .trim('-')
            .ifBlank { "my-shop-project" }
        val fileName = "$safeName.zip"
        val outFile = File(context.cacheDir, fileName)

        ZipOutputStream(BufferedOutputStream(FileOutputStream(outFile))).use { zos ->
            // 1. Write root index.html for instant GitHub Pages & Browser launch
            val rootIndexEntry = ZipEntry("$safeName/index.html")
            zos.putNextEntry(rootIndexEntry)
            zos.write(previewHtml.toByteArray(Charsets.UTF_8))
            zos.closeEntry()

            // 2. Write live standalone preview HTML
            val previewEntry = ZipEntry("$safeName/live-preview.html")
            zos.putNextEntry(previewEntry)
            zos.write(previewHtml.toByteArray(Charsets.UTF_8))
            zos.closeEntry()

            // 3. Write all structured source files (including .github/workflows/build-apk.yml & deploy-pages.yml)
            val writtenPaths = mutableSetOf("$safeName/index.html", "$safeName/live-preview.html")
            files.forEach { projFile ->
                val entryPath = "$safeName/${projFile.path.trimStart('/')}"
                if (writtenPaths.add(entryPath)) {
                    val entry = ZipEntry(entryPath)
                    zos.putNextEntry(entry)
                    zos.write(projFile.content.toByteArray(Charsets.UTF_8))
                    zos.closeEntry()
                }
            }

            // 4. Write README with BASO Studio metadata, APK instructions & GitHub Pages guide
            val readmeContent = """
# $safeName — Generated by BASO AI Builder (ستۆدیۆی فریلانسەر)

- **Author**: BASO Studio (باسۆ)
- **Files Included**: ${writtenPaths.size + 1}
- **🌐 Live Website (GitHub Pages)**: Push this repository to GitHub — `.github/workflows/deploy-pages.yml` and root `index.html` are pre-configured!
- **📲 Android APK Build**: `.github/workflows/build-apk.yml` automatically compiles an installable `.apk` on GitHub Actions and publishes it to GitHub Releases.
            """.trimIndent()
            zos.putNextEntry(ZipEntry("$safeName/README.md"))
            zos.write(readmeContent.toByteArray(Charsets.UTF_8))
            zos.closeEntry()
        }

        val kb = (outFile.length() / 1024.0).coerceAtLeast(1.2)
        val sizeStr = String.format("%.1f KB • Ready (APK + Web + GitHub)", kb)
        ZipExportResult(
            zipFile = outFile,
            fileName = fileName,
            readableSize = sizeStr,
            fileCount = files.size + 3
        )
    }

    fun shareOrSaveZipFile(context: Context, zipFile: File) {
        val uri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            zipFile
        )
        val shareIntent = Intent(Intent.ACTION_SEND).apply {
            type = "application/zip"
            putExtra(Intent.EXTRA_STREAM, uri)
            putExtra(Intent.EXTRA_SUBJECT, zipFile.name)
            putExtra(Intent.EXTRA_TEXT, "پڕۆژەی دروستکراو لەلایەن BASO AI Builder: ${zipFile.name}")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        val chooser = Intent.createChooser(shareIntent, "دابەزاندن یان هاوبەشکردنی ${zipFile.name}").apply {
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        context.startActivity(chooser)
    }

    suspend fun exportStandaloneAppHtml(
        context: Context,
        projectSlug: String,
        previewHtml: String
    ): File = withContext(Dispatchers.IO) {
        val safeName = projectSlug.lowercase()
            .replace(Regex("[^a-z0-9-_]"), "-")
            .trim('-')
            .ifBlank { "baso-app" }
        val htmlFile = File(context.cacheDir, "$safeName-standalone-app.html")
        htmlFile.writeText(previewHtml, Charsets.UTF_8)
        htmlFile
    }

    fun shareStandaloneAppHtml(context: Context, htmlFile: File) {
        val uri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            htmlFile
        )
        val shareIntent = Intent(Intent.ACTION_SEND).apply {
            type = "text/html"
            putExtra(Intent.EXTRA_STREAM, uri)
            putExtra(Intent.EXTRA_SUBJECT, htmlFile.name)
            putExtra(Intent.EXTRA_TEXT, "ئەپ و وێبسایتی سەربەخۆ لەلایەن BASO Studio: ${htmlFile.name}")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        val chooser = Intent.createChooser(shareIntent, "دابەزاندن و کردنەوەی ئەپی سەربەخۆ (${htmlFile.name})").apply {
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        context.startActivity(chooser)
    }
}
